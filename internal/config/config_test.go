func TestDefaultConfig(t *testing.T) {
	cfg := DefaultConfig()
	if cfg.Server.Port != 8080 {
		t.Errorf("expected default port 8080, got %d", cfg.Server.Port)
	}
	if cfg.Database.Type != "sqlite" {
		t.Errorf("expected default database type sqlite, got %s", cfg.Database.Type)
	}
	if err := cfg.Validate(); err != nil {
		t.Fatalf("default config failed validation: %v", err)
	}
}

func TestLoadWithFileAndEnvOverrides(t *testing.T) {
	tempDir := t.TempDir()
	configPath := filepath.Join(tempDir, "config.toml")

	tomlContent := `
[server]
host = "127.0.0.1"
port = 9090
base_url = "http://bam.test:9090"

[database]
type = "sqlite"
dsn = "custom.db"

[storage]
local_path = "./custom_uploads"
`
	if err := os.WriteFile(configPath, []byte(tomlContent), 0o600); err != nil {
		t.Fatalf("writing temp config: %v", err)
	}

	// 1. Verify file load
	cfg, err := Load(configPath)
	if err != nil {
		t.Fatalf("Load failed: %v", err)
	}
	if cfg.Server.Port != 9090 {
		t.Errorf("expected port 9090, got %d", cfg.Server.Port)
	}
	if cfg.Server.Host != "127.0.0.1" {
		t.Errorf("expected host 127.0.0.1, got %s", cfg.Server.Host)
	}

	// 2. Verify env overrides take precedence
	t.Setenv("BAM_SERVER_PORT", "9999")
	t.Setenv("BAM_DB_PATH", "/tmp/reaper_state/test.db")

	cfg2, err := Load(configPath)
	if err != nil {
		t.Fatalf("Load with env overrides failed: %v", err)
	}
	if cfg2.Server.Port != 9999 {
		t.Errorf("expected overridden port 9999, got %d", cfg2.Server.Port)
	}
	if cfg2.Database.DSN != "/tmp/reaper_state/test.db?_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)" {
		t.Errorf("expected overridden DSN, got %s", cfg2.Database.DSN)
	}
}

func TestValidationErrors(t *testing.T) {
	cfg := DefaultConfig()
	cfg.Server.Port = -1
	if err := cfg.Validate(); err == nil {
		t.Error("expected validation error for negative port")
	}

	cfg = DefaultConfig()
	cfg.Database.Type = "oracle"
	if err := cfg.Validate(); err == nil {
		t.Error("expected validation error for unsupported db type")
	}
}

func TestPrinterDevices(t *testing.T) {
	if cfg := DefaultConfig(); len(cfg.Printers.Devices) != 0 {
		t.Errorf("device connections allowed by default: %v", cfg.Printers.Devices)
	}

	configPath := filepath.Join(t.TempDir(), "config.toml")
	if err := os.WriteFile(configPath, []byte("[printers]\ndevices = [\"/dev/usb/lp*\"]\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := Load(configPath)
	if err != nil || len(cfg.Printers.Devices) != 1 || cfg.Printers.Devices[0] != "/dev/usb/lp*" {
		t.Fatalf("loaded %v, %v", cfg, err)
	}
	t.Setenv("BAM_PRINTERS_DEVICES", "/dev/usb/lp0,/dev/ulpt0")
	if cfg, err := Load(configPath); err != nil || len(cfg.Printers.Devices) != 2 || cfg.Printers.Devices[1] != "/dev/ulpt0" {
		t.Errorf("environment override gave %v, %v", cfg.Printers.Devices, err)
	}

	for _, bad := range []string{"dev/usb/lp*", "/dev/usb/lp["} {
		cfg := DefaultConfig()
		cfg.Printers.Devices = []string{bad}
		if err := cfg.Validate(); err == nil {
			t.Errorf("pattern %q accepted", bad)
		}
	}
}

func TestOldConfigWithSessionSecretStillLoads(t *testing.T) {
	// session_secret was generated by `bam init` but never used, and has been
	// removed; configuration files written before then must keep working.
	configPath := filepath.Join(t.TempDir(), "config.toml")
	old := "[server]\nport = 9090\nsession_secret = \"0123456789abcdef\"\n"
	if err := os.WriteFile(configPath, []byte(old), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := Load(configPath)
	if err != nil {
		t.Fatalf("loading a config with session_secret: %v", err)
	}
	if cfg.Server.Port != 9090 {
		t.Errorf("port = %d, want 9090", cfg.Server.Port)
	}
}

func TestMCPSetting(t *testing.T) {
	dir := t.TempDir()
	load := func(toml string) (*Config, error) {
		path := filepath.Join(dir, "config.toml")
		if err := os.WriteFile(path, []byte(toml), 0o600); err != nil {
			t.Fatal(err)
		}
		return Load(path)
	}

	// A file from before the setting existed keeps the endpoint on.
	cfg, err := load("[server]\nport = 8080\n")
	if err != nil || !cfg.MCP.Enabled {
		t.Fatalf("older file: %v %+v", err, cfg)
	}
	if cfg, err = load("[mcp]\nenabled = false\n"); err != nil || cfg.MCP.Enabled {
		t.Errorf("turned off: %v %+v", err, cfg.MCP)
	}

	for v, want := range map[string]bool{"false": false, "off": false, "0": false, "TRUE": true, "on": true} {
		t.Setenv("BAM_MCP_ENABLED", v)
		if cfg, err = load(""); err != nil || cfg.MCP.Enabled != want {
			t.Errorf("BAM_MCP_ENABLED=%s: %v %v", v, err, cfg)
		}
	}
	t.Setenv("BAM_MCP_ENABLED", "nope")
	if _, err = load(""); err == nil {
		t.Error("BAM_MCP_ENABLED=nope was accepted")
	}

	// bam init writes the table out, so people see it.
	path := filepath.Join(dir, "written.toml")
	if err := DefaultConfig().SaveTOML(path); err != nil {
		t.Fatal(err)
	}
	if data, _ := os.ReadFile(path); !strings.Contains(string(data), "[mcp]") || !strings.Contains(string(data), "enabled = true") {
		t.Errorf("written config:\n%s", data)
	}
}

func TestStorageSettings(t *testing.T) {
	dir := t.TempDir()
	load := func(toml string) (*Config, error) {
		path := filepath.Join(dir, "config.toml")
		if err := os.WriteFile(path, []byte(toml), 0o600); err != nil {
			t.Fatal(err)
		}
		return Load(path)
	}

	// A file from before backends existed keeps its directory.
	cfg, err := load("[storage]\nlocal_path = \"/var/lib/bam/uploads\"\n")
	if err != nil || cfg.Storage.Backend != StorageLocal || cfg.Storage.LocalPath != "/var/lib/bam/uploads" {
		t.Fatalf("older file: %v %+v", err, cfg.Storage)
	}

	s3 := "[storage]\nbackend = \"s3\"\n[storage.s3]\nendpoint = \"http://minio:9000\"\nbucket = \"bam\"\nprefix = \"site\"\npath_style = true\naccess_key_id = \"AK\"\nsecret_access_key = \"SK\"\n"
	cfg, err = load(s3)
	if err != nil || cfg.Storage.Backend != StorageS3 || cfg.Storage.S3.Prefix != "site/" || !cfg.Storage.S3.PathStyle || cfg.Storage.S3.Bucket != "bam" {
		t.Fatalf("s3: %v %+v", err, cfg.Storage)
	}

	// Each setting from the environment, the keys too.
	for env, v := range map[string]string{"BAM_STORAGE_BACKEND": "s3", "BAM_STORAGE_S3_ENDPOINT": "https://s3.example.org", "BAM_STORAGE_S3_REGION": "eu-west-2",
		"BAM_STORAGE_S3_BUCKET": "other", "BAM_STORAGE_S3_PREFIX": "a/b/", "BAM_STORAGE_S3_PATH_STYLE": "off",
		"BAM_STORAGE_S3_ACCESS_KEY_ID": "AK2", "BAM_STORAGE_S3_SECRET_ACCESS_KEY": "SK2"} {
		t.Setenv(env, v)
	}
	cfg, err = load(s3)
	if want := (S3Config{Endpoint: "https://s3.example.org", Region: "eu-west-2", Bucket: "other", Prefix: "a/b/", AccessKeyID: "AK2", SecretAccessKey: "SK2"}); err != nil || cfg.Storage.S3 != want {
		t.Errorf("from the environment: %v %+v", err, cfg.Storage.S3)
	}
	t.Setenv("BAM_STORAGE_S3_PATH_STYLE", "sideways")
	if _, err := load(s3); err == nil {
		t.Error("BAM_STORAGE_S3_PATH_STYLE=sideways was accepted")
	}
	for _, env := range []string{"BAM_STORAGE_BACKEND", "BAM_STORAGE_S3_ENDPOINT", "BAM_STORAGE_S3_REGION", "BAM_STORAGE_S3_BUCKET", "BAM_STORAGE_S3_PREFIX",
		"BAM_STORAGE_S3_PATH_STYLE", "BAM_STORAGE_S3_ACCESS_KEY_ID", "BAM_STORAGE_S3_SECRET_ACCESS_KEY"} {
		t.Setenv(env, "")
	}

	for what, c := range map[string]struct{ toml, want string }{
		"an unknown backend": {"[storage]\nbackend = \"floppy\"\n", "unsupported storage backend"},
		"s3 without its settings": {"[storage]\nbackend = \"s3\"\n",
			"storage.s3.access_key_id, storage.s3.bucket, storage.s3.endpoint, storage.s3.secret_access_key"},
		"an endpoint with no scheme":  {strings.Replace(s3, "http://minio:9000", "minio:9000", 1), "must be an http:// or https:// address"},
		"an endpoint with no host":    {strings.Replace(s3, "http://minio:9000", "http://", 1), "must be an http:// or https:// address"},
		"a prefix leaving the bucket": {strings.Replace(s3, `prefix = "site"`, `prefix = "../site"`, 1), "storage.s3.prefix"},
		"no directory":                {"[storage]\nlocal_path = \"\"\n", "local_path cannot be empty"},
	} {
		if _, err := load(c.toml); err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: %v, want it to say %q", what, err, c.want)
		}
	}
}
