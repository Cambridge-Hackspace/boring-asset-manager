"""Writes internal/archive/tables.go, the tables an archive holds (README
§2.3), from a migrated SQLite database: each archived table, in the order a
restore writes them, with its kind of information, columns, types and key.

What is decided by hand is here: ORDER (every archived table, its kind, and
the order), JSON (text columns holding JSON), SECRET (columns kept in auth/)
and BY_KEY. A table a migration adds must be put in ORDER, or in the
archive's Excluded list with why; TestTheRegistryMatchesTheSchema fails until
it is, and until this has been run again.

    go run ./cmd/bam migrate --config <a config whose database is x.db>
    python3 tools/archive/tables.py x.db internal/archive/tables.go
"""
import os
import sqlite3
import sys

db = sys.argv[1]
out = sys.argv[2]
c = sqlite3.connect(db)

ORDER = [
    ('reports', 'KindReports'),
    ('scopes', 'KindCatalog'), ('relation_types', 'KindCatalog'), ('fields', 'KindCatalog'), ('asset_actions', 'KindCatalog'),
    ('categories', 'KindCatalog'), ('category_fields', 'KindCatalog'), ('category_actions', 'KindCatalog'),
    ('category_relation_types', 'KindCatalog'), ('category_scopes', 'KindCatalog'),
    ('templates', 'KindLabels'), ('images', 'KindLabels'), ('category_label_templates', 'KindLabels'),
    ('icon_palette', 'KindIcons'), ('icon_settings', 'KindIcons'), ('icon_library', 'KindIcons'), ('category_icons', 'KindIcons'),
    ('icon_revisions', 'KindIcons'), ('icon_param_bindings', 'KindIcons'), ('icon_text_bindings', 'KindIcons'),
    ('roles', 'KindPeople'), ('role_permissions', 'KindPeople'), ('role_permission_scopes', 'KindPeople'), ('users', 'KindPeople'),
    ('user_roles', 'KindPeople'), ('user_role_scopes', 'KindPeople'),
    ('assets', 'KindAssets'), ('asset_categories', 'KindAssets'), ('asset_field_values', 'KindAssets'), ('asset_generator_keys', 'KindAssets'),
    ('asset_links', 'KindAssets'), ('asset_placements', 'KindAssets'), ('asset_loans', 'KindAssets'), ('asset_photos', 'KindAssets'),
    ('events', 'KindAssets'),
    ('flows', 'KindFlows'), ('flow_filings', 'KindFlows'),
    ('settings', 'KindSettings'), ('label_stock', 'KindSettings'), ('printers', 'KindSettings'), ('printer_pools', 'KindSettings'),
    ('printer_pool_members', 'KindSettings'), ('notification_channels', 'KindSettings'), ('spool_jobs', 'KindSettings'),
    ('spool_batches', 'KindSettings'), ('spool_job_members', 'KindSettings'), ('spool_entries', 'KindSettings'),
    ('sessions', 'KindAuth'), ('oauth_clients', 'KindAuth'), ('oauth_codes', 'KindAuth'), ('api_tokens', 'KindAuth'),
    ('api_token_roles', 'KindAuth'), ('api_token_role_scopes', 'KindAuth'),
]
JSON = {
    'fields': {'options'}, 'events': {'payload'}, 'reports': {'spec'}, 'templates': {'layout_json'},
    'printers': {'options'}, 'notification_channels': {'options', 'events'}, 'oauth_clients': {'redirect_uris'},
    'flows': {'definition'}, 'icon_settings': {'stroke_widths', 'reserved', 'limits', 'states'},
    'category_icons': {'draft_errors'}, 'icon_library': {'draft_errors'},
}
SECRET = {'users': ['password_hash', 'totp_secret'], 'notification_channels': ['options']}
# Grants are written by permission key, which is the same on every
# instance; permission IDs are not.
BY_KEY = {'role_permissions', 'role_permission_scopes'}


def coltype(t, table, name):
    if name in JSON.get(table, ()):
        return 'JSON'
    t = t.upper()
    if t.startswith('VARCHAR') or t == 'TEXT':
        return 'Text'
    if t in ('INTEGER', 'BIGINT'):
        return 'Int'
    if t in ('DOUBLE PRECISION', 'REAL'):
        return 'Float'
    if t == 'BOOLEAN':
        return 'Bool'
    if t == 'TIMESTAMP':
        return 'Time'
    sys.exit(f'{table}.{name}: no type for {t}')


lines = ['// Code generated by tools/archive/tables.py; DO NOT EDIT.', '// TestTheRegistryMatchesTheSchema checks it against the migrations.', '',
         'package archive', '', '// Tables are the tables an archive holds, in the order a restore writes', '// them: each after those its rows name.',
         'var Tables = []Table{']
for name, kind in ORDER:
    cols = c.execute(f'pragma table_info({name})').fetchall()
    key = [x[1] for x in sorted((x for x in cols if x[5]), key=lambda x: x[5])]
    parts = []
    for x in cols:
        cname, ctype = x[1], coltype(x[2], name, x[1])
        if name in BY_KEY and cname == 'permission_id':
            cname = 'permission_key'
            key = ['permission_key' if k == 'permission_id' else k for k in key]
        parts.append(f'{{"{cname}", {ctype}}}')
    lines.append(f'\t{{Name: "{name}", Kind: {kind}, Key: []string{{{", ".join(chr(34)+k+chr(34) for k in key)}}},')
    fields = [('Columns', f'[]Column{{{", ".join(parts)}}}')]
    if name in SECRET:
        fields.append(('Secret', f'[]string{{{", ".join(chr(34)+k+chr(34) for k in SECRET[name])}}}'))
    if name in BY_KEY:
        fields.append(('ByPermissionKey', 'true'))
    # Aligned as gofmt aligns them.
    width = max(len(f) for f, _ in fields) + 1
    for f, v in fields:
        lines.append(f'\t\t{(f + ":").ljust(width)} {v},')
    lines.append('\t},')
lines.append('}')
missing = {r[0] for r in c.execute("select name from sqlite_master where type='table' and name not like 'sqlite_%'")} - {n for n, _ in ORDER}
open(out, 'w', encoding='utf-8', newline='').write('\n'.join(lines) + '\n')
print('not archived:', sorted(missing))
